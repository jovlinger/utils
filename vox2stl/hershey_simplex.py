def hershey_strokes(letter: str) -> LetterStrokes:
    if letter in HERSHEY_DIGITS:
        return HERSHEY_DIGITS[letter]
    key = letter.upper()
    if key in HERSHEY_UPPER:
        return HERSHEY_UPPER[key]
    raise KeyError(f"no Hershey strokes for {letter!r}")
