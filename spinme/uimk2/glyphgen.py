#!/usr/bin/env python3
"""Host-side glyph generator: font path + pixel size -> flash table (C header).

Usage: glyphgen.py FONT_PATH PIXEL_SIZE OUT_HEADER

Steps: metrics (max ascent/descent -> H, B), render each glyph with no
antialiasing on an 8x grid, cut 8x8 boxes to alpha = filled*255/64, trim to
ink columns. The device never rasterizes.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

SS = 8  # supersampling factor per axis
CHARSET = [chr(c) for c in range(0x20, 0x7F)]


def load_font(path, size):
    return ImageFont.truetype(path, size * SS)


def render_grid(font, ch, ascent_px, h_px, pad_px, width_px):
    """Render ch (no antialiasing) onto a 1-bit grid; baseline at row ascent_px*SS."""
    img = Image.new("1", (width_px * SS, h_px * SS), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"
    draw.text((pad_px * SS, ascent_px * SS), ch, font=font, fill=1, anchor="ls")
    return img


def metrics(font, size, charset=CHARSET):
    """Return (ascent, descent) in output pixels over the whole charset."""
    big = size * 4
    asc = desc = 0
    for ch in charset:
        img = Image.new("1", (big * SS, big * 2 * SS), 0)
        draw = ImageDraw.Draw(img)
        draw.fontmode = "1"
        draw.text((size * SS, big * SS), ch, font=font, fill=1, anchor="ls")
        bb = img.getbbox()
        if bb is None:
            continue
        asc = max(asc, -((bb[1] - big * SS) // SS))  # ceil((base-top)/SS)
        desc = max(desc, -((big * SS - bb[3]) // SS))  # ceil((bottom-base)/SS)
    return asc, desc


def coverage(img, h_px):
    """Cut an SSxSS-box grid into alpha bytes; returns list of columns' bytes by row."""
    w_px = img.width // SS
    px = img.load()
    rows = []
    for y in range(h_px):
        row = []
        for x in range(w_px):
            filled = 0
            for yy in range(SS):
                for xx in range(SS):
                    if px[x * SS + xx, y * SS + yy]:
                        filled += 1
            row.append(filled * 255 // (SS * SS))
        rows.append(row)
    return rows


def build_glyph(font, ch, size, ascent, h_px):
    pad = size
    wide = size * 4
    img = render_grid(font, ch, ascent, h_px, pad, wide)
    rows = coverage(img, h_px)
    cols = [x for x in range(wide) if any(r[x] for r in rows)]
    if not cols:
        adv = max(1, round(font.getlength(ch) / SS))
        return adv, [0] * (adv * h_px)
    lo, hi = cols[0], cols[-1]
    w = hi - lo + 1
    return w, [rows[y][x] for y in range(h_px) for x in range(lo, hi + 1)]


def generate(font_path, size):
    """Return (H, B, table, blob); table entries are (codepoint, width, offset)."""
    font = load_font(font_path, size)
    asc, desc = metrics(font, size)
    h_px = asc + desc
    table = []
    blob = []
    for ch in CHARSET:
        w, data = build_glyph(font, ch, size, asc, h_px)
        table.append((ord(ch), w, len(blob)))
        blob.extend(data)
    return h_px, asc, table, blob


def write_header(path, h_px, base, table, blob):
    lines = [
        "/* Generated by glyphgen.py. Do not edit. */",
        "#include <stdint.h>",
        "#define GLYPH_H %d" % h_px,
        "#define GLYPH_B %d" % base,
        "#define GLYPH_COUNT %d" % len(table),
        "typedef struct { uint16_t codepoint; uint16_t width; uint32_t offset; } GlyphEntry;",
        "static const GlyphEntry glyph_table[GLYPH_COUNT] = {",
    ]
    for cp, w, off in table:
        lines.append("  {0x%04X, %d, %d}," % (cp, w, off))
    lines.append("};")
    lines.append("static const uint8_t glyph_alpha[%d] = {" % len(blob))
    for i in range(0, len(blob), 16):
        lines.append("  " + ",".join(str(b) for b in blob[i:i + 16]) + ",")
    lines.append("};")
    with open(path, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")


def main(argv):
    if len(argv) != 4:
        sys.stderr.write(__doc__)
        return 2
    h_px, base, table, blob = generate(argv[1], int(argv[2]))
    write_header(argv[3], h_px, base, table, blob)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
