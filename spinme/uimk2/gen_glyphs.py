#!/usr/bin/env python3
"""Host-side glyph generator for the uimk2 flash font table.

Usage: gen_glyphs.py FONT_PATH PIXEL_SIZE OUT_C

Renders every codepoint of the character set (printable ASCII, 0x20..0x7E)
from FONT_PATH with no antialiasing at 8 * PIXEL_SIZE, then cuts each glyph
into output pixels of 8x8 samples. Alpha is filled * 255 // 64; RGB is white
and is not stored.

Metrics: over the whole character set, ascent is the most ink rows above the
baseline and descent the most below it, both in output pixels (rounded up to
whole pixels). H = ascent + descent and B = ascent. Every box is H rows tall
with the baseline on row B: rows 0..B-1 are above the baseline.

Width: the span of output columns that hold ink, with the 8x8 grid aligned to
the glyph's leftmost inked sample. A codepoint with no ink (the space) takes
its advance width, rounded to whole pixels, and is all zero alpha.

OUT_C is a C99 source that includes uimk2_glyphs.h and defines the table
{codepoint, width, offset} sorted by codepoint plus the alpha bytes, one box
per entry, row-major, width * H bytes at offset.
"""

import sys

from PIL import Image, ImageDraw, ImageFont

SS = 8  # samples per output pixel, each axis
CHARSET = [chr(c) for c in range(0x20, 0x7F)]


def render_samples(font, ch, size_hi):
    """Bilevel render of ch with its baseline origin at (size_hi, 2*size_hi).

    Returns (img, origin_x, origin_y); img is mode '1', 1 = inked sample.
    """
    side = size_hi * 4
    ox, oy = size_hi, 2 * size_hi
    img = Image.new("1", (side, side), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"
    draw.text((ox, oy), ch, font=font, fill=1, anchor="ls")
    return img, ox, oy


def ceil_div(a, b):
    return -(-a // b)


def generate(font_path, px):
    """Return (H, B, entries); entries are (codepoint, width, alpha bytes)."""
    size_hi = px * SS
    font = ImageFont.truetype(font_path, size_hi)
    renders = {}
    asc_hi = 0
    desc_hi = 0
    for ch in CHARSET:
        img, ox, oy = render_samples(font, ch, size_hi)
        bbox = img.getbbox()
        renders[ch] = (img, ox, oy, bbox)
        if bbox is None:
            continue
        x0, y0, x1, y1 = bbox
        if x0 < SS or y0 < SS or x1 > img.width - SS or y1 > img.height - SS:
            raise SystemExit("glyph %r is too close to the canvas edge" % ch)
        asc_hi = max(asc_hi, oy - y0)
        desc_hi = max(desc_hi, y1 - oy)
    ascent = ceil_div(asc_hi, SS)
    descent = ceil_div(desc_hi, SS)
    h = ascent + descent
    b = ascent
    entries = []
    for ch in CHARSET:
        img, ox, oy, bbox = renders[ch]
        if bbox is None:
            width = int(round(font.getlength(ch) / SS))
            entries.append((ord(ch), width, bytes(width * h)))
            continue
        x0, _, x1, _ = bbox
        width = ceil_div(x1 - x0, SS)
        top = oy - b * SS  # sample row of output row 0
        pix = img.load()
        alpha = bytearray(width * h)
        for row in range(h):
            for col in range(width):
                filled = 0
                for sy in range(top + row * SS, top + (row + 1) * SS):
                    for sx in range(x0 + col * SS, x0 + (col + 1) * SS):
                        if pix[sx, sy]:
                            filled += 1
                alpha[row * width + col] = filled * 255 // 64
        entries.append((ord(ch), width, bytes(alpha)))
    return h, b, entries


def emit_c(font_path, px, h, b, entries):
    out = []
    out.append(
        "/* Generated by gen_glyphs.py from %s at %d px. Do not edit. */"
        % (font_path.replace("*/", "* /"), px)
    )
    out.append('#include "uimk2_glyphs.h"')
    out.append("")
    out.append("const uint16_t uimk2_glyph_h = %d;" % h)
    out.append("const uint16_t uimk2_glyph_b = %d;" % b)
    out.append("const uint16_t uimk2_glyph_count = %d;" % len(entries))
    out.append("")
    out.append("const uimk2_glyph_entry uimk2_glyph_table[%d] = {" % len(entries))
    offset = 0
    for cp, width, alpha in entries:
        out.append("    {0x%04X, %d, %d}," % (cp, width, offset))
        offset += len(alpha)
    out.append("};")
    out.append("")
    total = max(offset, 1)
    out.append("const uint8_t uimk2_glyph_alpha[%d] = {" % total)
    blob = b"".join(a for _, _, a in entries) or b"\0"
    for i in range(0, len(blob), 16):
        out.append("    " + ", ".join(str(v) for v in blob[i : i + 16]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) != 4:
        sys.stderr.write("usage: gen_glyphs.py FONT_PATH PIXEL_SIZE OUT_C\n")
        return 2
    font_path, px_s, out_c = argv[1], argv[2], argv[3]
    px = int(px_s)
    if px <= 0:
        sys.stderr.write("PIXEL_SIZE must be positive\n")
        return 2
    h, b, entries = generate(font_path, px)
    with open(out_c, "w", encoding="ascii") as f:
        f.write(emit_c(font_path, px, h, b, entries))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
