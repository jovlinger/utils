#!/usr/bin/env python3
"""Host-side glyph generator for the uimk2 follow view.

Usage: gen_glyphs.py FONT PIXEL_SIZE OUT_HEADER

Rasterizes the printable ASCII set from FONT at PIXEL_SIZE. Each glyph is
drawn with no antialiasing on a grid SUB times the pixel size in each axis,
and that grid is cut into SUB x SUB boxes, one per output pixel. A box's alpha
is filled * 255 / 64 (integer floor). The table keeps one shared height H and
baseline row B for every glyph, and trims each glyph to its ink columns.
The device never rasterizes; it reads the emitted C header.
"""

import math
import os
import sys

from PIL import Image, ImageDraw, ImageFont

SUB = 8
FALLBACK = "?"
CHARSET = [chr(c) for c in range(0x20, 0x7F)]


class Table:
    """Flash glyph table: entries are (codepoint, width, offset) into alpha."""

    def __init__(self, px, height, baseline, entries, alpha):
        self.px = px
        self.height = height
        self.baseline = baseline
        self.entries = entries
        self.alpha = alpha


def _font(path, px):
    return ImageFont.truetype(path, SUB * px, index=0)


def _raster(cols, rows, font, ch, origin_x, baseline_row):
    """One glyph, mono (no antialiasing), at sample resolution."""
    im = Image.new("1", (cols, rows), 0)
    ImageDraw.Draw(im).text(
        (origin_x, baseline_row), ch, font=font, fill=1, anchor="ls"
    )
    return im


def _metrics(font, px):
    """Return (H, B): shared box height and baseline row, in pixels."""
    cols = 3 * SUB * px
    rows = 4 * SUB * px
    base = 2 * SUB * px
    up = 0
    down = 0
    for ch in CHARSET:
        box = _raster(cols, rows, font, ch, SUB * px, base).getbbox()
        if box is None:
            continue
        up = max(up, base - box[1])
        down = max(down, box[3] - base)
    ascent = math.ceil(up / SUB)
    descent = math.ceil(down / SUB)
    return ascent + descent, ascent


def _glyph_box(font, ch, px, height, baseline):
    """Trimmed alpha box for ch, or None when the glyph has no ink."""
    cols = 3 * SUB * px
    rows = height * SUB
    im = _raster(cols, rows, font, ch, SUB * px, baseline * SUB).convert("L")
    data = im.tobytes()
    ncols = cols // SUB
    counts = []
    for r in range(height):
        row = []
        for c in range(ncols):
            filled = 0
            for sr in range(r * SUB, r * SUB + SUB):
                start = sr * cols + c * SUB
                filled += data[start:start + SUB].count(255)
            row.append(filled)
        counts.append(row)
    ink = [any(counts[r][c] for r in range(height)) for c in range(ncols)]
    if not any(ink):
        return None
    first = ink.index(True)
    last = ncols - 1 - ink[::-1].index(True)
    alpha = bytes(
        counts[r][c] * 255 // 64
        for r in range(height)
        for c in range(first, last + 1)
    )
    return last - first + 1, alpha


def build(path, px):
    """Build the glyph table for FONT at PIXEL_SIZE px."""
    if px < 1:
        raise ValueError("pixel size must be at least 1")
    font = _font(path, px)
    height, baseline = _metrics(font, px)
    entries = []
    alpha = bytearray()
    for ch in CHARSET:
        box = _glyph_box(font, ch, px, height, baseline)
        if box is None:
            width = int(round(font.getlength(ch) / SUB))
            data = bytes(height * width)
        else:
            width, data = box
        entries.append((ord(ch), width, len(alpha)))
        alpha += data
    return Table(px, height, baseline, entries, bytes(alpha))


def emit(table, font_path, out_path):
    """Write the table as a C header with a flash array and an entry array."""
    if max(width for _, width, _ in table.entries) > 255:
        raise ValueError("glyph wider than 255 pixels")
    if len(table.alpha) > 65535:
        raise ValueError("alpha blob larger than 65535 bytes")
    lines = [
        "/* Generated by gen_glyphs.py from %s at %d px. Do not edit. */"
        % (os.path.basename(font_path), table.px),
        "#ifndef UIMK2_GLYPHS_GEN_H",
        "#define UIMK2_GLYPHS_GEN_H",
        "",
        "#include <stdint.h>",
        "",
        "#define GLYPH_PIXEL_SIZE %d" % table.px,
        "#define GLYPH_HEIGHT %d" % table.height,
        "#define GLYPH_BASELINE %d" % table.baseline,
        "#define GLYPH_FALLBACK %d" % ord(FALLBACK),
        "",
        "typedef struct {",
        "    uint16_t cp;",
        "    uint8_t width;",
        "    uint16_t offset;",
        "} GlyphEntry;",
        "",
        "static const uint8_t glyph_alpha[%d] = {" % len(table.alpha),
    ]
    for i in range(0, len(table.alpha), 16):
        chunk = table.alpha[i:i + 16]
        lines.append("    " + ", ".join("%d" % b for b in chunk) + ",")
    lines.append("};")
    lines.append("")
    lines.append("static const GlyphEntry glyph_table[%d] = {" % len(table.entries))
    for cp, width, offset in table.entries:
        lines.append("    {%d, %d, %d}," % (cp, width, offset))
    lines.append("};")
    lines.append("")
    lines.append("#endif /* UIMK2_GLYPHS_GEN_H */")
    lines.append("")
    with open(out_path, "w", encoding="ascii") as fh:
        fh.write("\n".join(lines))


def main(argv):
    if len(argv) != 4:
        sys.stderr.write("usage: gen_glyphs.py FONT PIXEL_SIZE OUT_HEADER\n")
        return 2
    font_path, px, out_path = argv[1], int(argv[2]), argv[3]
    emit(build(font_path, px), font_path, out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
