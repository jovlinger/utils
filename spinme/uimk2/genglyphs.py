#!/usr/bin/env python3
"""Host-side glyph generator for uimk2.

usage: genglyphs.py FONT_PATH PIXEL_SIZE OUT.h

Renders ASCII 0x20..0x7E with no antialiasing on a grid 8x the pixel size in
each axis, cuts 8x8 boxes (alpha = filled*255/64, RGB white on device), and
trims each box to its ink columns. Every box has height H with the baseline on
row B. The device never rasterizes.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

SS = 8
CHARSET = [chr(c) for c in range(0x20, 0x7F)]
PAD = 4  # pixel columns of left margin on the scratch grid


def load_font(path, size):
    """Font at 8x the pixel size. Index 0 of a collection is used."""
    return ImageFont.truetype(path, size * SS, index=0)


def metrics(font):
    """Return (ascent, descent, H, B) in pixels over the whole character set."""
    asc = 0
    desc = 0
    for ch in CHARSET:
        if ch == " ":
            continue
        _, top, _, bottom = font.getbbox(ch, anchor="ls")
        asc = max(asc, -top)
        desc = max(desc, bottom)
    ascent = -(-asc // SS)
    descent = -(-desc // SS)
    return ascent, descent, ascent + descent, ascent


def render_grid(font, ch, h, b):
    """Binary 8x grid for ch: list of rows, each a list of 0/1.

    Width is a margin plus the advance plus a right margin; the baseline sits
    at grid row 8*b.
    """
    adv = int(font.getlength(ch))
    gw = (PAD * 2) * SS + adv + SS
    img = Image.new("1", (gw, h * SS), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((PAD * SS, b * SS), ch, font=font, fill=1, anchor="ls")
    px = img.load()
    return [[1 if px[x, y] else 0 for x in range(gw)] for y in range(h * SS)], gw


def cut_alpha(grid, gw, h):
    """Cut 8x8 boxes. Returns rows of alpha bytes, h rows, gw//8 columns."""
    cols = gw // SS
    rows = []
    for py in range(h):
        row = []
        for pxl in range(cols):
            filled = 0
            for gy in range(SS):
                line = grid[py * SS + gy]
                for gx in range(SS):
                    filled += line[pxl * SS + gx]
            row.append(filled * 255 // 64)
        rows.append(row)
    return rows


def glyph_box(font, ch, h, b):
    """Return (width, [h rows of width alpha bytes]) for one codepoint."""
    grid, gw = render_grid(font, ch, h, b)
    rows = cut_alpha(grid, gw, h)
    cols = len(rows[0])
    ink = [c for c in range(cols) if any(rows[r][c] for r in range(h))]
    if not ink:
        width = max(1, round(font.getlength(ch) / SS))
        return width, [[0] * width for _ in range(h)]
    lo, hi = ink[0], ink[-1]
    return hi - lo + 1, [row[lo:hi + 1] for row in rows]


def build(font_path, size):
    """Return dict with H, B, ascent, descent, entries, blob."""
    font = load_font(font_path, size)
    ascent, descent, h, b = metrics(font)
    entries = []
    blob = bytearray()
    for ch in CHARSET:
        width, rows = glyph_box(font, ch, h, b)
        entries.append((ord(ch), width, len(blob)))
        for row in rows:
            blob.extend(row)
    return {"H": h, "B": b, "ascent": ascent, "descent": descent,
            "entries": entries, "blob": bytes(blob)}


def emit_header(info, path):
    lines = ["/* generated by genglyphs.py; do not edit */",
             "#include <stdint.h>",
             "#define GLYPH_H %d" % info["H"],
             "#define GLYPH_B %d" % info["B"],
             "#define GLYPH_COUNT %d" % len(info["entries"]),
             "typedef struct { uint16_t codepoint; uint8_t width; "
             "uint32_t offset; } GlyphEntry;",
             "static const GlyphEntry kGlyphTable[GLYPH_COUNT] = {"]
    for cp, w, off in info["entries"]:
        lines.append("  {%d, %d, %d}," % (cp, w, off))
    lines.append("};")
    blob = info["blob"]
    lines.append("static const uint8_t kGlyphAlpha[%d] = {" % len(blob))
    for i in range(0, len(blob), 16):
        lines.append("  " + ",".join(str(v) for v in blob[i:i + 16]) + ",")
    lines.append("};")
    with open(path, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")


def main(argv):
    if len(argv) != 4:
        sys.stderr.write(__doc__)
        return 2
    info = build(argv[1], int(argv[2]))
    emit_header(info, argv[3])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
